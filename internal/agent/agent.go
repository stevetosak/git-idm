package agent

import (
	_ "embed"
	"errors"
	"os"
	"path/filepath"
	"strings"
)

//go:embed SKILL.md
var skill string

const marker = "<!-- generated by git-idm"

func Skill() string {
	return skill
}

func Instructions() string {
	_, body, found := strings.Cut(strings.TrimPrefix(skill, "---\n"), "\n---\n")
	if !found {
		return skill
	}
	_, body, _ = strings.Cut(body, "-->\n")
	return strings.TrimLeft(body, "\n")
}

func DefaultPath() string {
	dir := os.Getenv("CLAUDE_CONFIG_DIR")
	if dir == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return ""
		}
		dir = filepath.Join(home, ".claude")
	}
	return filepath.Join(dir, "skills", "git-idm", "SKILL.md")
}

func generated(path string) (bool, string, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return false, "", nil
	}
	if err != nil {
		return false, "", err
	}
	return strings.Contains(string(data), marker), string(data), nil
}

func Install(path string) (bool, error) {
	isOurs, current, err := generated(path)
	if err != nil {
		return false, err
	}
	if current != "" && !isOurs {
		return false, errors.New(path + " was not made by git-idm, remove it first")
	}
	if current == skill {
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	return true, os.WriteFile(path, []byte(skill), 0o644)
}

func Refresh(path string) (bool, error) {
	isOurs, current, err := generated(path)
	if err != nil || !isOurs || current == skill {
		return false, err
	}
	return true, os.WriteFile(path, []byte(skill), 0o644)
}

func Remove(path string) (bool, error) {
	isOurs, _, err := generated(path)
	if err != nil || !isOurs {
		return false, err
	}
	if err := os.Remove(path); err != nil {
		return false, err
	}
	_ = os.Remove(filepath.Dir(path))
	return true, nil
}

package gitgen

import (
	"fmt"
	"runtime"
	"sort"
	"strings"

	"github.com/stevetosak/git-idm/internal/config"
)

const (
	UnboundEmail = "no identity here, run: git-idm bind"
	BlockStart   = "# >>> git-idm (generated, do not edit) >>>"
	BlockEnd     = "# <<< git-idm <<<"
)

type Entry struct {
	Section    string
	Subsection string
	Key        string
	Value      string
}

func (e Entry) Name() string {
	if e.Subsection == "" {
		return e.Section + "." + e.Key
	}
	return e.Section + "." + e.Subsection + "." + e.Key
}

func IdentityEntries(name string, id config.Identity, bin string, strict bool) []Entry {
	entries := []Entry{
		{Section: "user", Key: "name", Value: id.Name},
		{Section: "user", Key: "email", Value: id.Email},
	}
	if id.SigningKey != "" {
		entries = append(entries,
			Entry{Section: "user", Key: "signingkey", Value: id.SigningKey},
			Entry{Section: "commit", Key: "gpgsign", Value: "true"},
			Entry{Section: "gpg", Key: "format", Value: signingFormat(id.SigningKey)},
		)
	} else {
		entries = append(entries,
			Entry{Section: "user", Key: "signingkey", Value: ""},
			Entry{Section: "commit", Key: "gpgsign", Value: "false"},
		)
	}
	switch {
	case bin != "" && strict:
		entries = append(entries,
			Entry{Section: "core", Key: "sshCommand", Value: SSHWrapper(bin, name, id)},
			Entry{Section: "ssh", Key: "variant", Value: "ssh"},
		)
	case SSHCommand(id) != "":
		entries = append(entries, Entry{Section: "core", Key: "sshCommand", Value: SSHCommand(id)})
	default:
		entries = append(entries, Entry{Section: "core", Key: "sshCommand", Value: "ssh"})
	}
	switch {
	case bin != "" && (id.GHConfigDir != "" || strict):
		entries = append(entries,
			Entry{Section: "credential", Subsection: "https://github.com", Key: "helper", Value: ""},
			Entry{Section: "credential", Subsection: "https://github.com", Key: "helper", Value: CredentialHelper(bin, name)},
		)
	case id.GHConfigDir != "":
		entries = append(entries,
			Entry{Section: "credential", Subsection: "https://github.com", Key: "helper", Value: ""},
			Entry{Section: "credential", Subsection: "https://github.com", Key: "helper",
				Value: "!GH_CONFIG_DIR=" + ShellQuote(config.ExpandHome(id.GHConfigDir)) + " " + ShellQuote(ghPath()) + " auth git-credential"},
		)
	}
	return entries
}

func CredentialHelper(bin, name string) string {
	q := ShellQuote(bin)
	return `!f() { if [ -x ` + q + ` ]; then exec ` + q + ` credential ` + ShellQuote(name) + ` "$@"; fi; ` +
		`echo "git-idm: "` + q + `" not found, git stops (run: git-idm doctor)" >&2; ` +
		`if [ "$1" = get ]; then echo quit=1; fi; }; f`
}

func ProtocolEntries(id config.Identity) []Entry {
	target := "https://github.com/"
	if id.Protocol == config.ProtocolSSH {
		target = "git@github.com:"
	}
	return []Entry{{Section: "url", Subsection: target, Key: "insteadOf", Value: "https://github.com/"}}
}

func RenderProtocol(id config.Identity) string {
	return renderEntries(ProtocolEntries(id))
}

func SSHCommand(id config.Identity) string {
	if id.SSHKey == "" {
		return ""
	}
	return "ssh -i " + ShellQuote(config.ExpandHome(id.SSHKey)) + " -o IdentitiesOnly=yes"
}

func SSHWrapper(bin, name string, id config.Identity) string {
	q := ShellQuote(bin)
	fallback := "ssh"
	if id.SSHKey != "" {
		fallback = SSHCommand(id)
	}
	return `f() { if [ -x ` + q + ` ]; then exec ` + q + ` ssh ` + ShellQuote(name) + ` "$@"; fi; ` +
		`case "$*" in *git-receive-pack*) echo "git-idm: "` + q + `" not found, the push stops (run: git-idm doctor)" >&2; exit 1;; esac; ` +
		`exec ` + fallback + ` "$@"; }; f`
}

func RenderIdentity(name string, id config.Identity, bin string, strict bool) string {
	return renderEntries(IdentityEntries(name, id, bin, strict))
}

func renderEntries(entries []Entry) string {
	var b strings.Builder
	b.WriteString("# generated by git-idm, do not edit\n")
	header := ""
	for _, e := range entries {
		h := "[" + e.Section + "]"
		if e.Subsection != "" {
			h = "[" + e.Section + " " + gitQuote(e.Subsection) + "]"
		}
		if h != header {
			b.WriteString(h + "\n")
			header = h
		}
		kv(&b, e.Key, e.Value)
	}
	return b.String()
}

func RenderBlock(c *config.Config, identityFile, protocolFile func(name string) string, hooksDir, bin string) string {
	var b strings.Builder
	b.WriteString(BlockStart + "\n")
	if hooksDir != "" {
		b.WriteString("[core]\n")
		kv(&b, "hooksPath", hooksDir)
		b.WriteString("[user]\n")
		kv(&b, "name", "")
		kv(&b, "email", UnboundEmail)
		kv(&b, "useConfigOnly", "true")
		if bin != "" && UsesGH(c) {
			b.WriteString("[credential \"https://github.com\"]\n")
			kv(&b, "helper", "")
			kv(&b, "helper", CredentialHelper(bin, ""))
			b.WriteString("[core]\n")
			kv(&b, "sshCommand", SSHWrapper(bin, "", config.Identity{}))
			b.WriteString("[ssh]\n")
			kv(&b, "variant", "ssh")
		}
	}
	rules := append([]config.Rule(nil), c.Rules...)
	sort.SliceStable(rules, func(i, j int) bool { return len(rules[i].Path) > len(rules[j].Path) })
	for _, r := range rules {
		fmt.Fprintf(&b, "[includeIf \"%s:%s\"]\n", gitdirCondition(), r.Path)
		kv(&b, "path", protocolFile(r.Identity))
	}
	sort.SliceStable(rules, func(i, j int) bool { return len(rules[i].Path) < len(rules[j].Path) })
	for _, r := range rules {
		fmt.Fprintf(&b, "[includeIf \"%s:%s\"]\n", gitdirCondition(), r.Path)
		kv(&b, "path", identityFile(r.Identity))
	}
	b.WriteString(BlockEnd + "\n")
	return b.String()
}

func ReplaceBlock(content, block string) (string, error) {
	lines := strings.SplitAfter(content, "\n")
	start, end := -1, -1
	for i, line := range lines {
		switch strings.TrimRight(line, "\r\n") {
		case BlockStart:
			if start != -1 {
				return "", fmt.Errorf("git-idm block start marker appears more than once")
			}
			start = i
		case BlockEnd:
			if end != -1 {
				return "", fmt.Errorf("git-idm block end marker appears more than once")
			}
			end = i
		}
	}
	if (start == -1) != (end == -1) || end < start {
		return "", fmt.Errorf("git-idm block markers are broken, fix them by hand")
	}
	rest := content
	if start != -1 {
		rest = strings.Join(lines[:start], "") + strings.Join(lines[end+1:], "")
	}
	rest = strings.TrimRight(rest, "\n")
	if rest == "" {
		return block, nil
	}
	return rest + "\n\n" + block, nil
}

func gitdirCondition() string {
	if runtime.GOOS == "darwin" || runtime.GOOS == "windows" {
		return "gitdir/i"
	}
	return "gitdir"
}

func signingFormat(key string) string {
	if strings.HasSuffix(key, ".pub") || strings.HasPrefix(key, "ssh-") || strings.HasPrefix(key, "key::") {
		return "ssh"
	}
	return "openpgp"
}

func ghPath() string {
	if p := RealGH(); p != "" {
		return p
	}
	return "gh"
}

func kv(b *strings.Builder, key, value string) {
	fmt.Fprintf(b, "\t%s = %s\n", key, gitQuote(value))
}

func gitQuote(v string) string {
	v = strings.ReplaceAll(v, `\`, `\\`)
	v = strings.ReplaceAll(v, `"`, `\"`)
	return `"` + v + `"`
}

func ShellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

package gitgen

import (
	"fmt"
	"os"
	"path/filepath"
)

const CheckCommand = "check-commit"

var HookNames = []string{
	"applypatch-msg", "pre-applypatch", "post-applypatch",
	"pre-commit", "pre-merge-commit", "prepare-commit-msg", "commit-msg", "post-commit",
	"pre-rebase", "post-checkout", "post-merge", "pre-push", "post-rewrite",
	"pre-receive", "update", "proc-receive", "post-receive", "post-update",
	"reference-transaction", "push-to-checkout", "pre-auto-gc", "sendemail-validate",
	"post-index-change", "p4-changelist", "p4-prepare-changelist", "p4-post-changelist", "p4-pre-submit",
}

func RenderDispatcher(bin string) string {
	q := ShellQuote(bin)
	return `#!/bin/sh
# generated by git-idm, do not edit
hook=${0##*/}
case "$hook" in
  pre-commit|pre-merge-commit)
    if [ -x ` + q + ` ]; then
      ` + q + ` ` + CheckCommand + ` || exit 1
    else
      echo "git-idm: identity guard skipped, "` + q + `" not found (run: git-idm doctor)" >&2
    fi
    ;;
esac
common=$(git rev-parse --git-common-dir 2>/dev/null) || exit 0
repo_hook="$common/hooks/$hook"
if [ -x "$repo_hook" ]; then
  exec "$repo_hook" "$@"
fi
exit 0
`
}

func (a *Applier) HooksDir() string {
	return filepath.Join(a.ConfigDir, "hooks")
}

func (a *Applier) syncHooks(enabled bool) ([]Change, error) {
	dir := a.HooksDir()
	if !enabled {
		if _, err := os.Stat(dir); os.IsNotExist(err) {
			return nil, nil
		}
		if err := os.RemoveAll(dir); err != nil {
			return nil, err
		}
		return []Change{{Path: dir, Action: "removed"}}, nil
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	script := RenderDispatcher(a.Bin)
	var changes []Change
	for _, name := range HookNames {
		path := filepath.Join(dir, name)
		current, err := readOptional(path)
		if err != nil {
			return changes, err
		}
		info, statErr := os.Stat(path)
		if current == script && statErr == nil && info.Mode().Perm()&0o111 != 0 {
			continue
		}
		if err := atomicWriteMode(path, script, 0o755); err != nil {
			return changes, err
		}
		changes = append(changes, Change{Path: path, Action: "wrote"})
	}
	if len(changes) > 1 {
		changes = []Change{{Path: dir, Action: fmt.Sprintf("wrote %d hooks in", len(changes))}}
	}
	return changes, nil
}

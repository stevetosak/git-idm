package gitgen

import (
	"errors"
	"os"
	"path/filepath"
	"strings"

	"github.com/stevetosak/git-idm/internal/config"
)

const (
	GeneratedMarker = "# generated by git-idm, do not edit"
	ShimEnv         = "GIT_IDM_GH_SHIM"
)

func DefaultBinDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".local", "bin")
}

func (a *Applier) ShimPath() string {
	if a.BinDir == "" {
		return ""
	}
	return filepath.Join(a.BinDir, "gh")
}

func RenderShim(bin string) string {
	q := ShellQuote(bin)
	return `#!/bin/sh
` + GeneratedMarker + `
if [ -x ` + q + ` ]; then
  ` + ShimEnv + `=$0
  export ` + ShimEnv + `
  exec ` + q + ` gh "$@"
fi
echo "git-idm: gh runs without git-idm, "` + q + `" not found (run: git-idm doctor)" >&2
self_dir=$(dirname -- "$0")
set -f
IFS=:
for dir in $PATH; do
  if [ "$dir" != "$self_dir" ] && [ -x "$dir/gh" ]; then
    exec "$dir/gh" "$@"
  fi
done
echo "git-idm: gh not found in PATH" >&2
exit 127
`
}

func IsShim(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	head := make([]byte, 128)
	n, _ := f.Read(head)
	return strings.Contains(string(head[:n]), GeneratedMarker)
}

func FindGH(path string, skip ...string) (string, error) {
	skipped := map[string]bool{}
	for _, s := range skip {
		if s == "" {
			continue
		}
		if resolved, err := filepath.EvalSymlinks(s); err == nil {
			skipped[resolved] = true
		}
	}
	for _, dir := range filepath.SplitList(path) {
		if !filepath.IsAbs(dir) {
			continue
		}
		candidate := filepath.Join(dir, "gh")
		info, err := os.Stat(candidate)
		if err != nil || !info.Mode().IsRegular() || info.Mode().Perm()&0o111 == 0 {
			continue
		}
		resolved, err := filepath.EvalSymlinks(candidate)
		if err != nil || skipped[resolved] || IsShim(resolved) {
			continue
		}
		return candidate, nil
	}
	return "", errors.New("gh is not installed or not in PATH")
}

func RealGH() string {
	path, err := FindGH(os.Getenv("PATH"))
	if err != nil {
		return ""
	}
	return path
}

func UsesGH(c *config.Config) bool {
	for _, id := range c.Identities {
		if id.GHConfigDir != "" {
			return true
		}
	}
	return false
}

func (a *Applier) syncShim(c *config.Config) ([]Change, error) {
	path := a.ShimPath()
	if path == "" {
		return nil, nil
	}
	if info, err := os.Stat(a.BinDir); err != nil || !info.IsDir() {
		return nil, nil
	}
	exists := false
	if _, err := os.Lstat(path); err == nil {
		exists = true
		if !IsShim(path) {
			return []Change{{Path: path, Action: "kept (not made by git-idm, gh does not follow the folder)"}}, nil
		}
	}
	_, ghErr := FindGH(os.Getenv("PATH"), path, a.Bin)
	if !UsesGH(c) || ghErr != nil {
		if !exists {
			return nil, nil
		}
		if err := os.Remove(path); err != nil {
			return nil, err
		}
		return []Change{{Path: path, Action: "removed"}}, nil
	}
	script := RenderShim(a.Bin)
	current, err := readOptional(path)
	if err != nil {
		return nil, err
	}
	if current == script {
		return nil, nil
	}
	if err := atomicWriteMode(path, script, 0o755); err != nil {
		return nil, err
	}
	action := "updated"
	if !exists {
		action = "created"
	}
	return []Change{{Path: path, Action: action}}, nil
}
